"""Run the real API in-process and export a read-only sample output page.

Run from the project root: python scripts/export_sample.py
Requires requirements-dev.txt. No key, network call or user resume is used.
"""

import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from fastapi.testclient import TestClient
from lxml import html
from app.main import app


def build():
    with tempfile.TemporaryDirectory() as temp:
        os.environ["DATABASE_PATH"] = str(Path(temp) / "demo.db")
        with TestClient(app) as client:
            resume = (ROOT / "examples/resume.txt").read_text()
            job = (ROOT / "examples/job_description.txt").read_text()
            uploaded = client.post(
                "/api/upload", files={"file": ("resume.txt", resume.encode())}
            )
            uploaded.raise_for_status()
            a = client.post(
                "/api/analysis",
                json={
                    "resume_text": uploaded.json()["resume_text"],
                    "job_description": job,
                    "target_role": "Python Backend Developer",
                },
            ).json()
            prompt = client.get("/api/prompts/3").json()
            first = prompt["versions"][0]
            second = client.post(
                "/api/prompts/3/versions",
                json={
                    "prompt_text": first["prompt_text"]
                    + "\nUse concise bullets and quote evidence for every match.",
                    "change_note": "Concise evidence bullets",
                },
            ).json()
            response = client.post(
                f"/api/analysis/{a['id']}/compare",
                json={
                    "version_a": first["id"],
                    "version_b": second["id"],
                    "mode": "demo",
                },
            )
            response.raise_for_status()
            result = response.json()
            for task_id in (1, 2, 4, 5, 6):
                run = client.post(
                    f"/api/analysis/{a['id']}/run-prompt",
                    json={"prompt_version_id": task_id, "mode": "demo"},
                )
                run.raise_for_status()
            runs = client.get(f"/api/analysis/{a['id']}/prompt-runs").json()
    output = {
        "analysis": a,
        "comparison": result,
        "runs": runs,
        "note": "Actual backend output using fictional sample inputs. Offline demo, not AI-generated.",
    }
    (ROOT / "docs/sample-output.json").write_text(json.dumps(output, indent=2) + "\n")
    document = html.fromstring((ROOT / "app/static/index.html").read_text())
    byid = lambda id: document.get_element_by_id(id)

    def text(id, value):
        byid(id).text = str(value)

    for script in document.xpath("//script"):
        script.getparent().remove(script)
    for link in document.xpath('//link[@rel="stylesheet"]'):
        link.getparent().remove(link)
    style = html.Element("style")
    style.text = (ROOT / "app/static/styles.css").read_text()
    document.find("head").append(style)
    for el in document.xpath("//button|//input|//textarea|//select"):
        el.set("disabled", "disabled")
    banner = byid("mode-banner")
    banner.clear()
    banner.set("id", "mode-banner")
    banner.set("class", "mode-banner")
    byid("mode-banner").text = (
        "READ-ONLY OUTPUT SNAPSHOT · Generated by the real Python API using fictional sample data. Offline demo, not a live AI response."
    )
    text("resume-text", a["resume_text"])
    text("job-description", a["job_description"])
    byid("target-role").set("value", a["target_role"])
    text("upload-label", "resume.txt · successfully parsed")
    text("analysis-state", "Sample analysis complete")
    byid("empty-report").set("hidden", "")
    byid("report").attrib.pop("hidden", None)
    r = a["report"]
    text("coverage", str(r["skill_coverage"]) + "%")
    text("matched-count", len(r["matched_skills"]))
    text("missing-count", len(r["not_demonstrated"]))
    text("similarity", str(r["lexical_similarity"]) + "%")
    text("coverage-title", "A solid foundation to build on")
    text(
        "coverage-description",
        f"{len(r['matched_skills'])} of {len(r['required_skills'])} detected job skills are explicitly mentioned in this resume.",
    )
    for id, skills in [
        ("matched-skills", r["matched_skills"]),
        ("missing-skills", r["not_demonstrated"]),
    ]:
        for skill in skills:
            span = html.Element("span")
            span.text = skill
            byid(id).append(span)
    for skill, quote in r["evidence"].items():
        box = html.Element("div", {"class": "evidence-item"})
        strong = html.Element("strong")
        strong.text = skill
        p = html.Element("p")
        p.text = quote
        box.extend([strong, p])
        byid("evidence").append(box)
    for section in document.xpath('//*[@id="view-studio" or @id="view-history"]'):
        section.getparent().remove(section)
    compare = html.Element("section", {"class": "card compare-section"})
    title = html.Element("h2")
    title.text = "Actual prompt comparison output"
    compare.append(title)
    note = html.Element("p", {"class": "helper"})
    note.text = "Same resume, job description and demo model. Outputs match because offline generation does not interpret prompt edits. Run Live AI in the application to test instruction changes."
    compare.append(note)
    grid = html.Element("div", {"class": "comparison-output"})
    for i, run in enumerate(result["runs"]):
        card = html.Element("article", {"class": "compare-result"})
        h = html.Element("h3")
        h.text = f"Version {i+1} · {run['model_name']}"
        card.append(h)
        detail = html.Element("details")
        summary = html.Element("summary")
        summary.text = "View exact prompt"
        pre = html.Element("pre")
        pre.text = run["prompt_text"]
        detail.extend([summary, pre])
        card.append(detail)
        pre = html.Element("pre", {"class": "output"})
        pre.text = run["output_text"]
        card.append(pre)
        grid.append(card)
    compare.append(grid)
    byid("view-analyzer").append(compare)
    (ROOT / "docs/sample-output.html").write_text(
        "<!doctype html>\n" + html.tostring(document, encoding="unicode")
    )
    print(
        json.dumps(
            {
                "skill_coverage": r["skill_coverage"],
                "matched_skills": r["matched_skills"],
                "not_demonstrated": r["not_demonstrated"],
                "lexical_similarity": r["lexical_similarity"],
                "prompt_runs": len(runs),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    build()
